"""Разбор фразы напоминания: «в четверг про врача» → дата, текст, время.

«Сегодня» здесь всегда фиксированное — понедельник 24 августа 2026. Тест,
который считает от настоящей даты, однажды упадёт в воскресенье или в
високосный год, и разбираться будет некому.
"""
import datetime as dt

import pytest

from johnny.dates import Reminder, parse, parse_with_fallback

ПН = dt.date(2026, 8, 24)      # понедельник


def разбор(фраза, today=ПН):
    return parse(фраза, today)


# -- ближайшие дни --

@pytest.mark.parametrize("слово,сдвиг", [("сегодня", 0), ("завтра", 1), ("послезавтра", 2)])
def test_сегодня_завтра_послезавтра(слово, сдвиг):
    найдено = разбор(f"{слово} про врача")
    assert найдено.date == ПН + dt.timedelta(days=сдвиг)
    assert найдено.text == "врача"


def test_через_сколько_то_дней():
    assert разбор("через 3 дня забрать посылку").date == ПН + dt.timedelta(days=3)


def test_через_неделю_без_числа():
    assert разбор("через неделю позвонить в банк").date == ПН + dt.timedelta(days=7)


def test_через_две_недели():
    assert разбор("через 2 недели к стоматологу").date == ПН + dt.timedelta(days=14)


def test_через_месяц_упирается_в_последний_день():
    # 31 января + месяц — это 28 февраля, а не 3 марта.
    assert parse("через месяц оплатить", dt.date(2026, 1, 31)).date == dt.date(2026, 2, 28)


def test_через_год():
    assert разбор("через год продлить права").date == dt.date(2027, 8, 24)


# -- дни недели --

def test_в_четверг_это_ближайший_четверг():
    assert разбор("в четверг про врача").date == dt.date(2026, 8, 27)


def test_день_недели_в_свой_же_день_это_следующая_неделя():
    # Ошибиться в эту сторону безопаснее: напоминание придёт позже, а не в прошлом.
    assert parse("в понедельник про зал", ПН).date == ПН + dt.timedelta(days=7)


def test_в_следующую_пятницу_это_ещё_на_неделю_дальше():
    ближайшая = разбор("в пятницу про отчет").date
    assert разбор("в следующую пятницу про отчет").date == ближайшая + dt.timedelta(days=7)


@pytest.mark.parametrize("день", ["среду", "пятницу", "субботу", "воскресенье", "вторник"])
def test_дни_недели_в_винительном_падеже_тоже_понимаются(день):
    assert разбор(f"в {день} про врача") is not None


def test_во_вторник_с_предлогом_во():
    assert разбор("во вторник про врача").date == dt.date(2026, 8, 25)


# -- числа и месяцы --

def test_пятнадцатого_сентября_словами():
    # Дату голосом называют порядковым числительным почти всегда.
    assert разбор("пятнадцатого сентября день рождения у мамы").date == dt.date(2026, 9, 15)


def test_составное_порядковое_число():
    assert разбор("двадцать первого декабря про подарки").date == dt.date(2026, 12, 21)


def test_число_цифрами_с_месяцем():
    assert разбор("15 сентября про врача").date == dt.date(2026, 9, 15)


def test_прошедшая_дата_без_года_переносится_на_следующий_год():
    # «Напомни 15 марта», сказанное в августе, — это про март следующего года.
    assert разбор("15 марта про налоги").date == dt.date(2027, 3, 15)


def test_дата_точками():
    assert разбор("15.09 про врача").date == dt.date(2026, 9, 15)


def test_дата_точками_с_годом():
    assert разбор("01.03.2027 про страховку").date == dt.date(2027, 3, 1)


def test_дата_в_iso():
    assert разбор("2027-03-01 про страховку").date == dt.date(2027, 3, 1)


def test_несуществующее_число_не_разбирается():
    assert разбор("32 сентября про врача") is None


# -- время --

def test_время_с_двоеточием():
    найдено = разбор("в четверг в 14:30 про врача")
    assert (найдено.time, найдено.text) == ("14:30", "врача")


def test_время_словом_вечера():
    assert разбор("завтра в 8 вечера позвонить маме").time == "20:00"


def test_время_словом_утра():
    assert разбор("завтра в 9 утра к врачу").time == "09:00"


def test_часы_без_части_суток():
    assert разбор("завтра в 15 часов к врачу").time == "15:00"


def test_через_три_дня_это_не_время():
    # «в 3» внутри «через 3 дня» не должно превратиться в 03:00.
    найдено = разбор("через 3 дня забрать посылку")
    assert найдено.time == ""


def test_кривое_время_не_ломает_разбор():
    найдено = разбор("завтра в 99:99 про врача")
    assert найдено is not None and найдено.time == ""


# -- повторы и предупреждения --

def test_каждый_год():
    найдено = разбор("каждый год 15 сентября день рождения у мамы")
    assert (найдено.repeat, найдено.date) == ("yearly", dt.date(2026, 9, 15))


def test_каждый_понедельник_это_еженедельно_с_ближайшего():
    найдено = разбор("каждый понедельник вынести мусор")
    assert (найдено.repeat, найдено.date) == ("weekly", ПН)


def test_ежемесячно():
    assert разбор("каждый месяц 10 числа заплатить").repeat == "monthly"


def test_предупредить_за_три_дня():
    найдено = разбор("15 сентября про врача предупреди за 3 дня")
    assert (найдено.warn, найдено.text) == (3, "врача")


def test_за_неделю_это_семь_дней():
    assert разбор("15 сентября про отчет за неделю").warn == 7


# -- отказы --

def test_фраза_без_даты_это_отказ():
    # Отказ лучше подмены: на отказ переспросят, подмену заметят поздно.
    assert разбор("про врача") is None


def test_дата_без_текста_это_тоже_отказ():
    assert разбор("в четверг") is None


def test_пустая_фраза():
    assert разбор("") is None and разбор("   ") is None


def test_прошедшая_дата_с_явным_годом_не_принимается():
    # Без года прошедшее число переносится на следующий год (см. тест выше);
    # отказ остаётся для случая, когда год назван прямо и он в прошлом.
    assert parse("01.01.2020 про врача", ПН) is None


def test_десятого_числа_без_названия_месяца():
    assert разбор("каждый месяц 10 числа заплатить за квартиру").date == dt.date(2026, 9, 10)


# -- чистка текста --

@pytest.mark.parametrize("фраза,текст", [
    ("завтра про врача", "врача"),
    ("завтра о встрече", "встрече"),
    ("завтра что надо забрать посылку", "забрать посылку"),
    ("завтра мне надо к врачу", "к врачу"),
    ("завтра, забрать посылку", "забрать посылку"),
])
def test_служебные_слова_в_текст_не_попадают(фраза, текст):
    assert разбор(фраза).text == текст


def test_ё_и_регистр_не_мешают():
    assert разбор("В Четверг про Подъём").text == "подъем"


# -- запасной путь через модель --

def test_свой_разбор_справился_модель_не_дёргается():
    звонки = []
    найдено = parse_with_fallback("завтра про врача", ПН, ask=lambda p: звонки.append(p) or "")
    assert найдено.date == ПН + dt.timedelta(days=1)
    assert звонки == []


def test_модель_подхватывает_то_чего_не_понял_парсер():
    ответ = '{"date": "2026-09-01", "text": "к стоматологу", "repeat": "once", "warn": 0}'
    найдено = parse_with_fallback("в первый понедельник осени к стоматологу", ПН, ask=lambda p: ответ)
    assert найдено == Reminder(dt.date(2026, 9, 1), "к стоматологу")


def test_модель_обернула_json_в_болтовню_и_это_переживается():
    ответ = 'Конечно!\n```json\n{"date": "2026-09-01", "text": "врач"}\n```\nГотово.'
    assert parse_with_fallback("непонятно когда врач", ПН, ask=lambda p: ответ).date == dt.date(2026, 9, 1)


def test_модель_вернула_дату_в_прошлом_и_ей_не_верят():
    ответ = '{"date": "2020-01-01", "text": "врач"}'
    assert parse_with_fallback("когда-то там врач", ПН, ask=lambda p: ответ) is None


def test_модель_вернула_мусор():
    for ответ in ("", "не знаю", "{}", '{"date": "завтра"}', '{"date": "2026-09-01"}'):
        assert parse_with_fallback("бормотание", ПН, ask=lambda p, r=ответ: r) is None


def test_модель_упала_а_джони_нет():
    def падает(_):
        raise RuntimeError("сеть")

    assert parse_with_fallback("бормотание", ПН, ask=падает) is None


def test_без_модели_запасного_пути_нет():
    assert parse_with_fallback("бормотание", ПН, ask=None) is None


def test_в_промпт_модели_уходит_сегодняшняя_дата():
    # Без неё «в четверг» модель считает от своей выдумки о текущем дне.
    промпты = []
    parse_with_fallback("непонятно", ПН, ask=lambda p: промпты.append(p) or "")
    assert "2026-08-24" in промпты[0] and "понедельник" in промпты[0]


def test_однозначный_час_без_части_суток_берётся():
    # «в 15» на 24-часовых часах двусмысленным не бывает.
    assert разбор("завтра в 15 покормить кота").time == "15:00"


def test_двусмысленный_час_остаётся_в_тексте_а_не_выдумывается():
    # «в 8» — это и утро, и вечер. Гадать нельзя, а терять сказанное — тем
    # более: пусть остаётся словами в самом напоминании.
    найдено = разбор("завтра в 8 покормить кота")
    assert найдено.time == ""
    assert "в 8" in найдено.text


def test_число_с_месяцем_не_съедается_разбором_времени():
    # «в 15 сентября» — дата, а не 15:00. Разбор времени идёт первым, и без
    # оговорки он забирал бы «в 15», после чего дата переставала находиться.
    найдено = разбор("в 15 сентября про врача")
    assert (найдено.date, найдено.time) == (dt.date(2026, 9, 15), "")


def test_десятое_число_не_съедается_разбором_времени():
    найдено = разбор("напоминай каждый месяц в 10 числа заплатить")
    assert найдено is not None and найдено.time == ""
