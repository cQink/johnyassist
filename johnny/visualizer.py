"""Геометрия кружка и пиксельной волны. Без Tk.

Панель рисует, этот модуль считает — ровно затем, чтобы «кружок зажигается на
имени» и «пульсирует под голос» можно было проверить тестом. На живом Tk такое
не проверить: анимацию глазами видно, а регрессию в ней — нет.

Пиксельная сетка не украшение, а требование дизайна (Y2K, дизеринг по краю):
радиус и высоты столбиков округляются до шага сетки, поэтому кружок «дышит»
ступеньками, а не плавно, и на любом кадре остаётся из целых клеток.
"""

import math
from dataclasses import dataclass

from . import activity

# Шаг пиксельной сетки в экранных точках. 4 — крупно настолько, что дизеринг
# читается, и мелко настолько, что кружок остаётся кружком, а не крестом.
CELL = 4

# Доли радиуса: покой и максимум. Кружок не схлопывается в точку на тишине —
# на его месте должен остаться след, иначе центр карточки выглядит пустым и
# сломанным, а не спокойным.
_MIN_SCALE = 0.42
_MAX_SCALE = 1.0

# Столбиков в волне по обе стороны от кружка. 28 — волна идёт через ВЕСЬ
# колодец осциллографа; на прежних 12 она занимала середину и читалась как
# украшение вокруг кружка, а не как показание прибора во всю ширину.
BARS = 28

# Насколько быстро бежит «дыхание» в фазах без голоса (радиан в секунду).
_BREATH_SPEED = 2.0


@dataclass(frozen=True)
class Frame:
    """Один кадр: что нарисовать, уже в клетках сетки.

    radius — в точках, кратен CELL. bars — высоты столбиков волны, тоже в
    точках и тоже кратны CELL; нули означают «столбик не рисуем». active —
    зажжён ли кружок: панель по нему выбирает лаймовый цвет вместо тусклого.
    """

    radius: int
    bars: tuple[int, ...]
    active: bool
    tone: str  # ключ палитры: "idle" | "wake" | "listen" | "think" | "speak" | "paused"


# Фазы, в которых кружок горит. Пауза сюда не входит намеренно: погасший
# кружок — единственное, что отличает «на паузе» от «слушает» на карточке,
# если человек не читает текст.
_LIT = frozenset({activity.WAKE, activity.LISTEN, activity.THINK, activity.SPEAK})


def frame(snapshot, tick: float, size: int, disc_size: int | None = None) -> Frame:
    """Кадр по снимку состояния.

    tick — время в секундах (monotonic), только для «дыхания»: в фазах без
    голоса кружок обязан шевелиться, иначе панель не отличить от скриншота.
    size — высота поля под ВОЛНУ: от неё считаются столбики.
    disc_size — сторона поля под КРУЖОК; None значит «то же, что size».

    Размеры разведены, потому что в колодце осциллографа они разные: волна
    идёт во всю высоту, а кружок остаётся небольшим. Пока они были одним
    числом, крупная волна тянула за собой кружок на пол-колодца.
    """
    phase = snapshot.phase
    level = max(0.0, min(1.0, snapshot.level))
    active = phase in _LIT
    # THINK — микрофон уже не слушают, уровень затухает в ноль, а показать
    # работу надо. Дыхание вместо голоса: та же амплитуда, только от времени.
    if phase in (activity.THINK, activity.WAKE) and level <= 0.05:
        level = 0.25 + 0.25 * (math.sin(tick * _BREATH_SPEED) + 1.0) / 2.0
    scale = _MIN_SCALE + (_MAX_SCALE - _MIN_SCALE) * (level if active else 0.0)
    half = (size if disc_size is None else disc_size) / 2.0
    radius = _snap(half * scale)
    return Frame(radius=radius, bars=_bars(level, tick, active, size), active=active, tone=phase)


def _bars(level: float, tick: float, active: bool, size: int) -> tuple[int, ...]:
    """Высоты столбиков волны — симметрично, максимум у центра.

    На тишине волна плоская (нули): «столбики стоят ровно» врало бы про
    входной сигнал, которого нет.
    """
    if not active or level <= 0.01:
        return (0,) * BARS
    top = size / 2.0
    out: list[int] = []
    for i in range(BARS):
        # Затухание от центра к краям + бегущая фаза, чтобы волна двигалась.
        falloff = 1.0 - (i / BARS) * 0.75
        wobble = 0.65 + 0.35 * math.sin(tick * 6.0 + i * 0.9)
        out.append(_snap(top * level * falloff * wobble))
    return tuple(out)


def _snap(value: float) -> int:
    """К сетке CELL, но не в ноль: клетка — минимум видимого."""
    cells = int(round(value / CELL))
    return max(1, cells) * CELL
