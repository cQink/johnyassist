"""Не дать Джони запуститься дважды одновременно.

ЖИВОЙ БАГ (2026-08-05): автозапуск и ручной запуск (ярлык) сработали в одну
секунду — два процесса Джони слушали ОДИН физический микрофон и реагировали
на одно и то же «Джони» одновременно. Это объяснило сразу несколько жалоб:
двойное проигрывание звука-подтверждения внахлёст («Да, сэр?» звучало
обрублено — второй процесс глушил начало своим же звуком поверх первого),
двойной вызов actions.duck_pulse (см. его собственный фикс того же дня) и
конкурирующую запись «ввод»-команды. Именованный мьютекс Windows —
стандартный приём: второй процесс видит, что мьютекс уже существует, и
завершается сам, до того как начнёт грузить тяжёлые модели.
"""

import win32api
import win32event
import winerror

_MUTEX_NAME = "Global\\JohnnyVoiceAssistant"

# Хендл держим на уровне модуля (не только внутри acquire) — иначе сборщик
# мусора закроет его вместе с локальной переменной, и мьютекс освободится
# ещё при живом процессе, сводя всю защиту на нет.
_handle = None


def acquire(name: str = _MUTEX_NAME, force: bool = False) -> bool:
    """True — этот процесс единственный и может продолжать запуск.

    False — другой процесс Джони уже держит мьютекс; вызывающий обязан
    завершиться, не трогая микрофон/модели. Хендл в этом случае сразу
    закрывается — он этому процессу не нужен.

    Если force=True, игнорируем существующий мьютекс и запускаем приложение
    вручную — это полезно для локального открытия UI после залипшего старого
    процесса.
    """
    global _handle
    handle = win32event.CreateMutex(None, False, name)
    already_running = win32api.GetLastError() == winerror.ERROR_ALREADY_EXISTS
    if already_running and not force:
        win32api.CloseHandle(handle)
        return False
    _handle = handle
    return True
