"""Модификатор фразы, выбирающий вкладку для открытия.

Отдельные команды вида «найди на ютубе * в этой вкладке» пришлось бы
дописывать к каждой из полусотни сайтовых команд — сто строк и вечная
обязанность помнить про вторую половину при каждой новой команде.
Модификатор снимается с фразы целиком, поэтому работает со всеми командами
сразу, включая будущие, и внутри цепочек тоже.
"""

# Хвосты в нижнем регистре: сравнение идёт по нормализованной строке.
_TAILS = ("в этой вкладке", "в текущей вкладке", "в этом окне")


def strip_tab_modifier(text: str) -> tuple[str, bool]:
    """«найди на ютубе кино в этой вкладке» → («найди на ютубе кино», False).

    Второе значение — открывать ли в НОВОЙ вкладке. Модификатора нет →
    (текст, True).

    Ищем модификатор ГДЕ УГОДНО, а не только в конце: в цепочке он оказывается
    в середине сам собой — «найди на ютубе кино в этой вкладке и включи первое
    видео». Обрезка только с хвоста такую фразу пропускала.
    """
    lowered = text.lower().strip()
    for tail in _TAILS:
        if tail in lowered:
            rest = " ".join(lowered.replace(tail, " ", 1).split())
            if rest:  # «в этой вкладке» само по себе командой не является
                return rest, False
    return text, True
