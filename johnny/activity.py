"""Живое состояние Джони для панели: фаза и громкость, одним снимком.

Кружок в панели обязан зажигаться на wake word и пульсировать под голос, а
значит UI нужно знать то, что знает цикл прослушивания. Прямого вызова между
ними нет и быть не может: цикл живёт в своём потоке, а трогать виджеты из
чужого потока нельзя — позвать даже after оттуда нельзя, он сам по себе вызов
в Tcl (та же причина, по которой ответы тулкитов ходят через очередь, см.
panel_tools.drain).

Поэтому здесь не колбэки, а доска объявлений: цикл пишет, панель читает по
своему таймеру. Панели может не быть вовсе (консольный режим, трей без
открытого окна) — писать в доску дешевле, чем каждый раз выяснять, есть ли
кому читать, и цикл прослушивания ничего про UI не знает.

Громкость затухает сама (см. _DECAY_PER_SECOND). Иначе кружок замирал бы
раздутым на последнем блоке речи: микрофон перестаёт присылать блоки, и
обновить уровень станет некому — «пульсация» превратилась бы в застывшее
пятно. Затухание считается в момент чтения, а не по таймеру: отдельный поток
ради одного числа не нужен, и без читателя он бы крутился впустую.
"""

import threading
import time
from dataclasses import dataclass

# Фазы. Строки, а не Enum: они уходят в UI как ключи палитры и попадают в
# логи — Enum пришлось бы разворачивать в .value в обоих местах.
IDLE = "idle"  # тишина, имя не звучало
WAKE = "wake"  # имя подтверждено, кружок зажигается
LISTEN = "listen"  # пишем команду с микрофона
THINK = "think"  # Whisper/модель считает, микрофон уже не при делах
SPEAK = "speak"  # Джони говорит сам
PAUSED = "paused"  # пауза из трея или панели

# Громкость, которую считаем «в полный голос». Замер 2026-07-27 (см.
# audio._SILENCE_RMS): речь с обычного расстояния 0.0012–0.0145, фон не выше
# 0.00065. Верх шкалы чуть выше самой громкой замеренной фразы, чтобы кружок
# доходил до края на крике, а не упирался в потолок на обычной речи.
_LOUD_RMS = 0.02

# На сколько уровень падает за секунду, если новых блоков нет. Считать надо от
# ПЕРИОДА БЛОКА (audio.BLOCK_FRAMES — 0.25с), а не от ощущения «быстро/медленно»:
# уровень обновляется ровно раз в блок, и за один зазор внутри слова кружок
# успевает провалиться на четверть этого значения.
#
# Прежние 2.5 были взяты на глаз и означали -0.625 за один блок — то есть
# кружок схлопывался больше чем наполовину в первом же промежутке между
# слогами, и max() в push_level, поставленный ровно против этого, ничего не
# спасал. 1.2 даёт -0.3 за блок: провал виден (это и есть пульсация), но не
# обвал, а с последнего блока речи кружок гаснет за 0.83с — раньше, чем
# закончится окно тишины в record_until_silence (1.2с).
_DECAY_PER_SECOND = 1.2


@dataclass(frozen=True)
class Snapshot:
    """Что показывать прямо сейчас.

    level уже с затуханием — панель не должна знать, когда пришёл последний
    блок, иначе эту арифметику пришлось бы повторить в каждом читателе.
    """

    phase: str
    level: float


_lock = threading.Lock()
_phase = IDLE
_level = 0.0
_at = 0.0  # monotonic, когда _level был записан


def set_phase(phase: str) -> None:
    """Отметить, чем Джони занят. Зовётся из цикла прослушивания."""
    global _phase
    with _lock:
        _phase = phase


def push_level(rms: float) -> None:
    """Отдать громкость очередного блока (RMS в тех же единицах, что audio).

    Берём максимум с затухшим прошлым значением, а не сырое новое: блоки по
    0.25с попадают и в тихие промежутки внутри слова, и кружок схлопывался бы
    между слогами. Затухание и так уведёт его вниз, когда речь кончится.
    """
    global _level, _at
    scaled = min(1.0, (max(0.0, rms) / _LOUD_RMS) ** 0.5)
    now = time.monotonic()
    with _lock:
        _level = max(scaled, _decayed(now))
        _at = now


def pulse(level: float) -> None:
    """Задать уровень напрямую — для фаз без микрофона.

    Пока говорит сам Джони, входной поток он же и заглушает (mic.flush в
    controller), так что пульсировать под его речь по RMS нечем: пульсацию
    рисует панель, а сюда кладётся только «сейчас звучит голос».
    """
    global _level, _at
    with _lock:
        _level = min(1.0, max(0.0, level))
        _at = time.monotonic()


def snapshot() -> Snapshot:
    """Фаза и уже затухший уровень. Зовётся из потока Tk по таймеру."""
    now = time.monotonic()
    with _lock:
        return Snapshot(_phase, _decayed(now))


def reset() -> None:
    """Погасить всё. Нужен тестам и остановке прослушивания."""
    global _phase, _level, _at
    with _lock:
        _phase = IDLE
        _level = 0.0
        _at = 0.0


def _decayed(now: float) -> float:
    """Уровень с поправкой на прошедшее время. Только под _lock."""
    if _level <= 0.0 or _at == 0.0:
        return 0.0
    faded = _level - (now - _at) * _DECAY_PER_SECOND
    return faded if faded > 0.0 else 0.0
